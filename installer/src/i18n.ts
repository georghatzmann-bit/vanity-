export type Lang = "de" | "en";

/** Beide Wörterbücher (für Tests und Werkzeuge) */
export const dictionaries = { de, en };
let lang: Lang = navigator.language?.toLowerCase().startsWith("de") ? "de" : "en";
const subs = new Set<() => void>();

export function setLang(l: Lang) {
  lang = l;
  document.documentElement.lang = l;
  subs.forEach((s) => s());
}
export function getLang() {
  return lang;
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const dict: unknown = lang === "de" ? de : en;
  let cur: unknown = dict;
  for (const p of key.split(".")) cur = cur && typeof cur === "object" ? (cur as Record<string, unknown>)[p] : undefined;
  let s = typeof cur === "string" ? cur : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
  return s;
}

export function useT() {
  useSyncExternalStore(
    (cb) => (subs.add(cb), () => subs.delete(cb)),
    () => lang,
  );
  return t;
}

/**
 * Bytes mit Einheit (Basis 1024). Die Einheit wechselt schon ab 1000 der kleineren Einheit – so gibt es
 * kein „1.023 KB“ mit Tausenderpunkt; ohne Gruppierung.
 */
export function formatBytes(b: number): string {
  if (!b || b < 0 || !Number.isFinite(b)) return "0 B";
  const u = ["B", "KB", "MB", "GB", "TB"];
  let i = 0;
  let v = b;
  while (v >= 1000 && i < u.length - 1) {
    v /= 1024;
    i++;
  }
  return `${v.toLocaleString(lang === "de" ? "de-DE" : "en-US", { maximumFractionDigits: i >= 2 ? 1 : 0, useGrouping: false })} ${u[i]}`;
}

/** Restzeit wie die übrigen Messwerte: „8 s“, „1 min 5 s“ (einmal gerundet, kein „1 min 60 s“) */
export function formatEta(s: number): string {
  if (!Number.isFinite(s) || s <= 0) return "";
  const r = Math.max(1, Math.round(s));
  if (r < 60) return `${r} s`;
  const m = Math.floor(r / 60);
  const sec = r % 60;
  return `${m} min ${sec} s`;
}
