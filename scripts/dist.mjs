#!/usr/bin/env node
// Builds the Windows installer release/Phoenix-Setup-<version>.exe on any host OS:
//   1. vite build                       -> dist/renderer
//   2. electron-builder --win nsis --x64 --publish never
//
// On Linux/macOS no Wine is needed: electron-builder (26.x) edits the exe resources with the
// pure-JS "resedit" and only runs Wine for ONE step – executing an intermediate installer that
// writes the uninstaller. We point ELECTRON_BUILDER_WINE_TOOLSET_DIR at a tiny fake "wine" that
// extracts that uninstaller with electron-builder's own pure-JS UninstallerReader instead (the
// code path electron-builder itself uses on macOS >= 10.15). Output is byte-identical to a
// real-Wine build. On Windows nothing of this is used.
//
// Usage: node scripts/dist.mjs [extra electron-builder args]   (npm run dist:linux-host)
// Env:   ELECTRON_MIRROR / ELECTRON_BUILDER_BINARIES_MIRROR – default to npmmirror.com unless set
//        PHOENIX_NO_MIRROR=1                 – use the official download hosts instead
//        ELECTRON_BUILDER_WINE_TOOLSET_DIR   – if set, it is respected (e.g. a real Wine toolset)
import { spawnSync } from 'node:child_process';
import { chmodSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const extraArgs = process.argv.slice(2);
const env = { ...process.env, CSC_IDENTITY_AUTO_DISCOVERY: 'false' };

if (env.PHOENIX_NO_MIRROR !== '1') {
  env.ELECTRON_MIRROR ||= 'https://npmmirror.com/mirrors/electron/';
  env.ELECTRON_BUILDER_BINARIES_MIRROR ||= 'https://npmmirror.com/mirrors/electron-builder-binaries/';
}

const WINE_SHIM = `#!/usr/bin/env node
// Fake "wine" for electron-builder (generated by scripts/dist.mjs). Called as: wine <installer.exe>
'use strict';
const path = require('path');
const installer = process.argv[2];
if (!installer || !/\\.exe$/i.test(installer) || process.argv.length !== 3) {
  console.error('[nowine] unexpected invocation: ' + process.argv.slice(2).join(' '));
  process.exit(2);
}
const uninstaller = path.join(path.dirname(installer), path.basename(installer, 'exe') + '__uninstaller.exe');
let mod;
for (const base of [process.env.PHOENIX_ROOT, process.cwd()].filter(Boolean)) {
  try { mod = require(require.resolve('app-builder-lib/out/targets/nsis/nsisUtil', { paths: [base] })); break; } catch {}
}
if (!mod || !mod.UninstallerReader) { console.error('[nowine] cannot resolve app-builder-lib UninstallerReader'); process.exit(3); }
mod.UninstallerReader.exec(installer, uninstaller)
  .then(() => console.log('[nowine] extracted ' + uninstaller))
  .catch((e) => { console.error('[nowine] failed: ' + ((e && e.stack) || e)); process.exit(1); });
`;

let shimDir = null;
if (process.platform !== 'win32' && !env.ELECTRON_BUILDER_WINE_TOOLSET_DIR) {
  shimDir = mkdtempSync(join(tmpdir(), 'phoenix-nowine-'));
  mkdirSync(join(shimDir, 'bin'));
  mkdirSync(join(shimDir, 'lib')); // electron-builder checks that lib/ and wine-home/ exist
  mkdirSync(join(shimDir, 'wine-home'));
  writeFileSync(join(shimDir, 'bin', 'wine'), WINE_SHIM);
  chmodSync(join(shimDir, 'bin', 'wine'), 0o755);
  env.ELECTRON_BUILDER_WINE_TOOLSET_DIR = shimDir;
  env.PHOENIX_ROOT = ROOT;
}

function run(label, script, args) {
  console.log(`\n> ${label}`);
  const r = spawnSync(process.execPath, [join(ROOT, 'node_modules', ...script.split('/')), ...args], {
    cwd: ROOT,
    env,
    stdio: 'inherit',
  });
  if (r.error) throw r.error;
  if (r.status !== 0) throw new Error(`${label} failed (exit ${r.status ?? r.signal})`);
}

const t0 = Date.now();
try {
  run('vite build', 'vite/bin/vite.js', ['build']);
  run('electron-builder --win nsis --x64', 'electron-builder/cli.js', ['--win', 'nsis', '--x64', '--publish', 'never', ...extraArgs]);
  if (extraArgs.length === 0) {
    const v = spawnSync(process.execPath, [join(ROOT, 'scripts', 'verify-dist.mjs')], { cwd: ROOT, stdio: 'inherit' });
    if (v.status !== 0) throw new Error('verify-dist failed');
  }
  console.log(`\nfertig in ${((Date.now() - t0) / 1000).toFixed(1)} s`);
} catch (e) {
  console.error(`\n${e.message}`);
  process.exitCode = 1;
} finally {
  if (shimDir) rmSync(shimDir, { recursive: true, force: true });
}
