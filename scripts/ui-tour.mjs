// Rundgang durch alle Seiten im Browser (Demo-Modus) mit Screenshots und Fehlerprotokoll.
// Aufruf: node scripts/ui-tour.mjs <basis-url> <ausgabe-ordner> [theme]
import { mkdirSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
let playwright;
try { playwright = require("playwright"); } catch { playwright = require("/opt/node22/lib/node_modules/playwright"); }
const [, , base = "http://localhost:1420/", out = "screens", theme = "nova"] = process.argv;
mkdirSync(out, { recursive: true });
const browser = await playwright.chromium.launch({ args: ["--autoplay-policy=no-user-gesture-required"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, locale: "de-DE" });
const errors = [];
page.on("pageerror", (e) => errors.push("pageerror: " + e.message));
page.on("console", (m) => { if (m.type() === "error" || m.type() === "warning") errors.push(m.type() + ": " + m.text()); });
await page.goto(base, { waitUntil: "networkidle" });
await page.waitForTimeout(5200);
const nova = (fn) => page.evaluate(fn);
await nova(`window.__nova.useSettings.getState().update({ theme: "${theme}", language: "de" })`);
await page.waitForTimeout(600);
const shot = async (name) => { await page.waitForTimeout(1400); await page.screenshot({ path: `${out}/${name}.png` }); console.log("📸", name); };
const go = async (route) => { await nova(`window.__nova.useUI.getState().navigate(${JSON.stringify(route)})`); };
await shot("01-home");
await go({ page: "library" }); await shot("02-library");
await page.mouse.move(420, 420); await page.waitForTimeout(500); await shot("03-library-hover");
const firstId = await nova(`window.__nova.useLibrary.getState().games[0].id`);
await go({ page: "game", id: firstId }); await shot("04-game");
await go({ page: "collections" }); await shot("05-collections");
await go({ page: "stats" }); await page.waitForTimeout(800); await shot("06-stats");
await page.mouse.wheel(0, 900); await shot("07-stats-scrolled");
await go({ page: "achievements" }); await shot("08-achievements");
await go({ page: "wishlist" }); await shot("09-wishlist");
await go({ page: "cleanup" }); await shot("10-cleanup");
await go({ page: "settings" }); await shot("11-settings");
await nova(`window.__nova.useUI.getState().setPalette(true)`); await page.keyboard.type("bal"); await shot("12-palette");
await page.keyboard.press("Escape"); await page.waitForTimeout(300);
await nova(`window.__nova.useUI.getState().setDice(true)`); await shot("13-dice");
await page.getByRole("button", { name: /Würfeln/ }).click(); await page.waitForTimeout(2200); await shot("14-dice-result");
await page.keyboard.press("Escape"); await page.waitForTimeout(300);
await nova(`window.__nova.useUI.getState().setScan(true)`); await shot("15-scan");
await page.keyboard.press("Escape"); await page.waitForTimeout(300);
await nova(`window.__nova.useUI.getState().setBigPicture(true)`); await shot("16-bigpicture");
await page.keyboard.press("ArrowRight"); await page.keyboard.press("ArrowRight"); await shot("17-bigpicture-move");
await page.keyboard.press("Escape"); await page.waitForTimeout(400);
await go({ page: "game", id: firstId });
await nova(`window.__nova.useLibrary.getState().launch(window.__nova.useLibrary.getState().games[0])`); await page.waitForTimeout(700); await shot("18-launch-ritual");
await page.waitForTimeout(2500); await shot("19-running");
await browser.close();
console.log(errors.length ? "\nFEHLER/WARNUNGEN:\n" + [...new Set(errors)].join("\n") : "\nKeine Fehler in der Konsole.");
